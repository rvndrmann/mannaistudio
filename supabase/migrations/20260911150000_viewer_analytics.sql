-- One row per person: every visit, every episode, everything they paid.
--
-- `episodes_after_first_visit` is the returning-viewer answer — episodes whose
-- first watch happened in a visit that was not their first. Someone who binges
-- four episodes on day one and never comes back scores zero; someone who came
-- back the next evening for episode five scores one. That is the difference
-- between an audience and a day of traffic, and no count of sessions or
-- purchases separates them on its own.
create or replace function public.admin_analytics_viewers(
    p_days int default 90,
    p_limit int default 200,
    p_search text default null
)
returns table (
    profile_id uuid,
    visitor_id uuid,
    full_name text,
    email text,
    avatar_url text,
    first_seen_at timestamptz,
    last_seen_at timestamptz,
    sessions int,
    page_views int,
    episodes_watched int,
    episodes_completed int,
    episodes_after_first_visit int,
    watch_days int,
    seconds_watched int,
    paid_episodes int,
    credits_spent int,
    season_passes int,
    credits_balance int,
    last_series_title text,
    last_episode_number int
)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_from timestamptz := now() - make_interval(days => greatest(coalesce(p_days, 90), 1));
    v_search text := nullif(btrim(coalesce(p_search, '')), '');
begin
    if not exists (select 1 from public.admin_users where id = auth.uid()) then
        raise exception 'Admin access required';
    end if;

    return query
    with sessions_in_window as (
        select s.*, coalesce(s.profile_id::text, s.visitor_id::text) as person
        from public.analytics_sessions s
        where s.started_at >= v_from
    ),
    people as (
        select sw.person,
               max(sw.profile_id::text)::uuid as profile_id,
               max(sw.visitor_id::text)::uuid as visitor_id,
               min(sw.started_at) as first_seen_at,
               max(sw.last_seen_at) as last_seen_at,
               count(*)::int as sessions,
               coalesce(sum(sw.page_views), 0)::int as page_views,
               -- The visit this person arrived on, which the "came back for a
               -- new episode" test below is measured against.
               (array_agg(sw.id order by sw.started_at))[1] as first_session_id
        from sessions_in_window sw
        group by sw.person
    ),
    views as (
        select coalesce(v.profile_id::text, v.visitor_id::text) as person,
               v.episode_id,
               min(v.started_at) as first_view_at,
               max(v.last_seen_at) as last_view_at,
               bool_or(v.completed) as completed,
               max(v.seconds_watched)::int as seconds_watched,
               (array_agg(v.session_id order by v.started_at))[1] as first_session_id
        from public.originals_episode_views v
        where v.started_at >= v_from
        group by 1, 2
    ),
    watch as (
        select vw.person,
               count(*)::int as episodes_watched,
               count(*) filter (where vw.completed)::int as episodes_completed,
               coalesce(sum(vw.seconds_watched), 0)::int as seconds_watched,
               count(distinct date_trunc('day', vw.first_view_at))::int as watch_days,
               max(vw.last_view_at) as last_view_at
        from views vw
        group by 1
    )
    select pe.profile_id,
           pe.visitor_id,
           p.full_name,
           p.email,
           p.avatar_url,
           pe.first_seen_at,
           pe.last_seen_at,
           pe.sessions,
           pe.page_views,
           coalesce(w.episodes_watched, 0),
           coalesce(w.episodes_completed, 0),
           (select count(*)::int from views vw
             where vw.person = pe.person
               and vw.first_session_id is distinct from pe.first_session_id),
           coalesce(w.watch_days, 0),
           coalesce(w.seconds_watched, 0),
           (select count(*)::int from public.originals_unlocks u where u.profile_id = pe.profile_id),
           (select coalesce(sum(u.credits_spent), 0)::int from public.originals_unlocks u where u.profile_id = pe.profile_id),
           (select count(*)::int from public.originals_season_passes sp where sp.profile_id = pe.profile_id),
           p.credits_balance,
           last_watch.series_title,
           last_watch.episode_number
    from people pe
    left join public.profiles p on p.id = pe.profile_id
    left join watch w on w.person = pe.person
    left join lateral (
        select se.title as series_title, e.episode_number
        from public.originals_episode_views v
        join public.originals_episodes e on e.id = v.episode_id
        join public.originals_series se on se.id = v.series_id
        where coalesce(v.profile_id::text, v.visitor_id::text) = pe.person
        order by v.last_seen_at desc
        limit 1
    ) last_watch on true
    where v_search is null
       or p.full_name ilike '%' || v_search || '%'
       or p.email ilike '%' || v_search || '%'
    order by pe.last_seen_at desc
    limit greatest(coalesce(p_limit, 200), 1);
end;
$$;

