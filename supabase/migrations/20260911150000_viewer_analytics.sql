-- Every purchase, newest first: who paid, for which episode, and how much.
-- Rentals and season passes in one list, because "which episodes has this
-- person paid for" has two answers and showing only unlocks understates it.
create or replace function public.admin_analytics_purchases(
    p_days int default 90,
    p_limit int default 300
)
returns table (
    kind text,
    profile_id uuid,
    full_name text,
    email text,
    avatar_url text,
    series_title text,
    episode_number int,
    episode_title text,
    credits_spent int,
    price_inr int,
    purchased_at timestamptz,
    expires_at timestamptz,
    watched boolean,
    percent_watched int
)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_from timestamptz := now() - make_interval(days => greatest(coalesce(p_days, 90), 1));
begin
    if not exists (select 1 from public.admin_users where id = auth.uid()) then
        raise exception 'Admin access required';
    end if;

    -- The union is wrapped in a named CTE rather than ordered directly. A
    -- UNION's own ORDER BY may only name a result column, and every column
    -- here is an expression — so the bare `purchased_at` resolved to the OUT
    -- parameter of that name and Postgres rejected the whole statement. The
    -- explicit column list gives the ordering something real to point at.
    return query
    with purchase_rows (
        kind, profile_id, full_name, email, avatar_url, series_title,
        episode_number, episode_title, credits_spent, price_inr,
        purchased_at, expires_at, watched, percent_watched
    ) as (
    (
        select 'episode'::text,
               u.profile_id,
               p.full_name,
               p.email,
               p.avatar_url,
               s.title,
               e.episode_number,
               e.title,
               u.credits_spent,
               null::int,
               u.created_at,
               u.expires_at,
               -- Bought and never opened is worth seeing on its own: it is a
               -- refund conversation, and it is invisible in a revenue total.
               exists (
                   select 1 from public.originals_episode_views v
                    where v.episode_id = u.episode_id and v.profile_id = u.profile_id
               ),
               (select max(case when coalesce(v.duration_seconds, 0) > 0
                                then least(100, (v.furthest_second * 100) / v.duration_seconds)
                                else 0 end)::int
                  from public.originals_episode_views v
                 where v.episode_id = u.episode_id and v.profile_id = u.profile_id)
        from public.originals_unlocks u
        join public.originals_episodes e on e.id = u.episode_id
        join public.originals_series s on s.id = e.series_id
        left join public.profiles p on p.id = u.profile_id
        where u.created_at >= v_from
    )
    union all
    (
        select 'season_pass'::text,
               sp.profile_id,
               p.full_name,
               p.email,
               p.avatar_url,
               s.title,
               null::int,
               null::text,
               null::int,
               sp.price_inr,
               sp.created_at,
               sp.expires_at,
               null::boolean,
               null::int
        from public.originals_season_passes sp
        join public.originals_series s on s.id = sp.series_id
        left join public.profiles p on p.id = sp.profile_id
        where sp.created_at >= v_from
    )
    )
    select pr.kind, pr.profile_id, pr.full_name, pr.email, pr.avatar_url,
           pr.series_title, pr.episode_number, pr.episode_title,
           pr.credits_spent, pr.price_inr, pr.purchased_at, pr.expires_at,
           pr.watched, pr.percent_watched
    from purchase_rows pr
    order by pr.purchased_at desc
    limit greatest(coalesce(p_limit, 300), 1);
end;
$$;

