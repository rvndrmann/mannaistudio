-- Everyone who has opened one episode, and what each of them did with it.
create or replace function public.admin_analytics_episode_viewers(
    p_episode_id uuid,
    p_limit int default 200
)
returns table (
    profile_id uuid,
    visitor_id uuid,
    full_name text,
    email text,
    avatar_url text,
    views int,
    first_watched_at timestamptz,
    last_watched_at timestamptz,
    seconds_watched int,
    percent_watched int,
    completed boolean,
    access text,
    credits_spent int,
    paid_at timestamptz,
    unlock_expires_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
begin
    if not exists (select 1 from public.admin_users where id = auth.uid()) then
        raise exception 'Admin access required';
    end if;

    return query
    with per_person as (
        select coalesce(v.profile_id::text, v.visitor_id::text) as person,
               -- A person who watched signed out and then signed in has rows
               -- both ways; max() picks up the account when one exists.
               max(v.profile_id::text)::uuid as profile_id,
               max(v.visitor_id::text)::uuid as visitor_id,
               count(*)::int as views,
               min(v.started_at) as first_watched_at,
               max(v.last_seen_at) as last_watched_at,
               max(v.seconds_watched)::int as seconds_watched,
               max(case when coalesce(v.duration_seconds, 0) > 0
                        then least(100, (v.furthest_second * 100) / v.duration_seconds)
                        else 0 end)::int as percent_watched,
               bool_or(v.completed) as completed,
               -- Paid beats free when the same person has both: the question
               -- is whether they ever bought it, not how they last opened it.
               max(case v.access when 'purchased' then 4 when 'pass' then 3
                                 when 'unlocked' then 2 else 1 end) as access_rank
        from public.originals_episode_views v
        where v.episode_id = p_episode_id
        group by 1
    )
    select pp.profile_id,
           pp.visitor_id,
           p.full_name,
           p.email,
           p.avatar_url,
           pp.views,
           pp.first_watched_at,
           pp.last_watched_at,
           pp.seconds_watched,
           pp.percent_watched,
           pp.completed,
           case pp.access_rank when 4 then 'purchased' when 3 then 'pass'
                               when 2 then 'unlocked' else 'free' end,
           u.credits_spent,
           u.created_at,
           u.expires_at
    from per_person pp
    left join public.profiles p on p.id = pp.profile_id
    left join public.originals_unlocks u
           on u.episode_id = p_episode_id and u.profile_id = pp.profile_id
    order by pp.last_watched_at desc
    limit greatest(coalesce(p_limit, 200), 1);
end;
$$;

