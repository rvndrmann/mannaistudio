-- The full history of one person: every visit and every episode, in order.
-- Reached from a row in the viewer table, which is where "did they come back"
-- turns into "come back to what".
create or replace function public.admin_analytics_viewer_history(
    p_profile_id uuid default null,
    p_visitor_id uuid default null,
    p_limit int default 100
)
returns table (
    kind text,
    happened_at timestamptz,
    session_id uuid,
    series_title text,
    episode_number int,
    episode_title text,
    percent_watched int,
    seconds_watched int,
    completed boolean,
    access text,
    path text,
    device text
)
language plpgsql
security definer
set search_path = public
as $$
begin
    if not exists (select 1 from public.admin_users where id = auth.uid()) then
        raise exception 'Admin access required';
    end if;
    if p_profile_id is null and p_visitor_id is null then
        raise exception 'A profile or a visitor is required';
    end if;

    -- Wrapped for the same reason as `admin_analytics_purchases` above: a
    -- UNION cannot be ordered by an expression column, and the bare name would
    -- have found the OUT parameter instead.
    return query
    with history_rows (
        kind, happened_at, session_id, series_title, episode_number,
        episode_title, percent_watched, seconds_watched, completed, access,
        path, device
    ) as (
    (
        select 'watch'::text,
               v.started_at,
               v.session_id,
               s.title,
               e.episode_number,
               e.title,
               case when coalesce(v.duration_seconds, 0) > 0
                    then least(100, (v.furthest_second * 100) / v.duration_seconds)::int
                    else null end,
               v.seconds_watched,
               v.completed,
               v.access,
               null::text,
               null::text
        from public.originals_episode_views v
        join public.originals_episodes e on e.id = v.episode_id
        join public.originals_series s on s.id = v.series_id
        where (p_profile_id is not null and v.profile_id = p_profile_id)
           or (p_profile_id is null and v.visitor_id = p_visitor_id)
    )
    union all
    (
        select 'visit'::text,
               ses.started_at,
               ses.id,
               null::text,
               null::int,
               null::text,
               null::int,
               null::int,
               null::boolean,
               null::text,
               ses.landing_path,
               ses.device
        from public.analytics_sessions ses
        where (p_profile_id is not null and ses.profile_id = p_profile_id)
           or (p_profile_id is null and ses.visitor_id = p_visitor_id)
    )
    )
    select hr.kind, hr.happened_at, hr.session_id, hr.series_title,
           hr.episode_number, hr.episode_title, hr.percent_watched,
           hr.seconds_watched, hr.completed, hr.access, hr.path, hr.device
    from history_rows hr
    order by hr.happened_at desc
    limit greatest(coalesce(p_limit, 100), 1);
end;
$$;

